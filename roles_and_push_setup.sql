-- نظام صيانة الإطفاء: فصل مسؤول النظام عن ملاحظ الإطفاء وتجهيز تخزين اشتراكات Push.
-- نفّذ بعد أخذ نسخة احتياطية ومراجعة أسماء الجداول الحالية.

-- 1) السماح بخمسة أدوار مميزة في profiles.role.
-- هذا لا يحوّل الحسابات الحالية تلقائياً؛ راجع كل حساب وحدد دوره الصحيح يدوياً.
DO $$
DECLARE c RECORD;
BEGIN
  FOR c IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.profiles'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%role%'
      AND (pg_get_constraintdef(oid) ILIKE '%admin%'
        OR pg_get_constraintdef(oid) ILIKE '%technician%'
        OR pg_get_constraintdef(oid) ILIKE '%department_head%'
        OR pg_get_constraintdef(oid) ILIKE '%safety_engineer%')
  LOOP
    EXECUTE format('ALTER TABLE public.profiles DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

ALTER TABLE public.profiles
  ADD CONSTRAINT profiles_role_allowed_check
  CHECK (role IN ('admin', 'fire_observer', 'safety_engineer', 'department_head', 'technician'));

COMMENT ON CONSTRAINT profiles_role_allowed_check ON public.profiles IS
  'Distinct application roles: admin=مسؤول النظام, fire_observer=ملاحظ الإطفاء, safety_engineer=مهندس الإطفاء, department_head=رئيس قسم الإطفاء, technician=فني الإطفاء';

-- 2) جدول تخزين اشتراك المتصفح. وجود الجدول وحده لا يرسل Push؛ يلزم مرسل خلفي ومفاتيح VAPID.
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  subscription jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "users manage own push subscriptions" ON public.push_subscriptions;
CREATE POLICY "users manage own push subscriptions"
  ON public.push_subscriptions
  FOR ALL TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.push_subscriptions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.push_subscriptions_id_seq TO authenticated;

